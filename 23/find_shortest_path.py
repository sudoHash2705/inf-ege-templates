# Пример для задачи КЕГЭ-32025
#
# Найдите и запишите в ответе целую часть длины кратчайшего пути из вершины с номером 4
# в вершину с номером 100.

import heapq
from collections import defaultdict
from dataclasses import dataclass


# Для того, чтобы решить задачу, нам нужно хранить в памяти информацию о рёбрах
# графика. Информация о ребре представляет из себя пару из двух чисел: вес ребра и
# номер конечной вершины.
#
# Конечно, можно сохранить эти числа в tuple или list, например `(123, 4)` где 123 --
# вес ребра, а 4 -- номер конечной вершины. Но в конкретно в данном случае использовать
# tuple или list будет очень неудобно, поскольку элементы из них можно доставать только
# по индексу: `edge[0] == 123`. Из-за этого во время задачи очень легко запутаться, на
# каком месте стоит какое число, или же просто промазать по клавише и вместо 0 написать
# 1.
#
# Поэтому, чтобы это предотвратить, для хранения нашей информации создадим класс Edge,
# потому что из объектов класса элементы можно доставать по понятному имени, а не по
# непонятному числу: `edge.weight == 123`. Кроме того, использование класса делает код
# этого шаблона более лёгким для понимания и восприятия.
#
# Поскольку единственное, что будет делать наш класс -- это хранить информацию, мы
# можем воспользоваться декоратором @dataclass из модуля dataclasses, чтобы он
# сэкономил нам время и автоматически создал для класса метод __init__ и прочие.
#
# Без @dataclass -- много писать:
# class Edge:
#     def __init__(self, weight: float, target: int) -> None:
#         self.weight = weight
#         self.target = target
#
# С @dataclass:
@dataclass(order=True)
class Edge:
    # Обратите внимание на параметр order=True при вызове @dataclass и на порядок, в
    # котором обьявляются атрибуты (weight и target). Скоро узнаете, зачем это нужно.
    weight: float  # Вес (длина) ребра
    target: int  # Конечная точка ребра


# В коде этого шаблона используются аннотации типов, как эти. Они нужны только лишь для
# того, чтобы сделать код понятнее и абсолютно никак не влияют на ход выполения
# программы. То есть, на экзамене их писать совершенно необязательно.

# Граф представим как dict, ключом которого будет являтся номер какой-то вершины, а
# значением -- список всех рёбер, исходящих из этой вершины. Например, такой граф:
#
#     |--> 1 --|
# 0 --|        |--> 3
#     |--> 2 --|
#
# будет сохранён в таком виде:
#
# graph: Graph = {
#     0: [Edge(555, 1), Edge(444, 2)],
#     1: [Edge(888, 3)],
#     2: [Edge(999, 3)],
# }
Graph = dict[int, list[Edge]]
Distances = dict[int, float]


# Нам нужно найти кратчайший путь в *ориентированном взвешенном графе*. Для этого
# отлично подойдёт алгоритм Дейкстры, представленный в данной функции. Она рассчитает
# кратчайшее расстояние от вершины с номером `start` до каждой вершины графа `graph`, и
# вернёт dict, ключом которого будет являться номер какой-то вершины графа, а
# значением -- расстояние до этой вершины из `start`.
def dijkstra(graph: Graph, start: int) -> Distances:
    # Создаём этот самый dict с расстояниями до каждой вершины. Расстояния, которые мы
    # ещё пока не вычислили будут равны бесконечности (float("inf")).
    #
    # Чтобы не создавать элементы вручную и избежать ошибок KeyError, воспользуемся
    # функцией defaultdict из модуля collections. При помощи неё можно создать dict,
    # который будет автоматически создавать несуществующие элементы из заданной функции
    # при первом обращении:
    #
    # >>> foo = defaultdict(lambda: float("inf"))
    # >>> len(foo)
    # 0
    # >>> foo[5]
    # inf
    # >>> len(foo)
    # 1
    # >>> # Элемент под ключом 5 был создан автоматически
    distances: Distances = defaultdict(lambda: float("inf"))

    # Расстояние до начальной точки равно 0, так как мы уже находимся в ней
    distances[start] = 0

    # Создадим приоритетную очередь (priority queue, heap queue), по которой будем
    # обозревать рёбра графа.
    #
    # Грубо говоря, приориетная очередь -- это такая коллекция, у которой наименьший
    # элемент всегда находится на первом месте. В Python с такими очередями можно
    # работать при помощи обыкновенного list и модуля heapq.
    #
    # С помощью функций в heapq можно добавлять и извлекать элементы из list,
    # автоматически сортируя этот list по возрастанию.
    #
    # А чтобы list возможно было отсортировать, нужно чтобы элементы в нём можно было
    # сравнивать между собой. Именно для этого мы добавили order=True в определение
    # класса Edge и поставили `weight` на первое место. Благодаря этому heapq сможет
    # автоматически сортировать рёбра по их весу.
    #
    # Сначала исследуем вершину `start`.
    queue = [Edge(0, start)]
    while queue:
        # heapq.heappop извлекает и удаляет из list наименьший элемент и сортирует его,
        # если нужно
        current_edge = heapq.heappop(queue)

        # Пропустить это ребро, если мы уже нашли более короткое расстояние до его
        # конечной точки
        if current_edge.weight > distances[current_edge.target]:
            continue

        # Исследуем все рёбра, исходящие из текущей вершины
        for neighbor in graph[current_edge.target]:
            neighbor_distance = current_edge.weight + neighbor.weight

            # Если мы нашли более короткое расстояние до соседа, сохраняем его в
            # `distances` и добавляем этого соседа в `queue`
            if neighbor_distance < distances[neighbor.target]:
                distances[neighbor.target] = neighbor_distance
                heapq.heappush(queue, Edge(neighbor_distance, neighbor.target))

    return distances


# Прочитаем граф из файла и сохраним его в dict вышеупомянутого формата
graph: Graph = defaultdict(list)
with open("input.txt") as file:
    # map трансформирует заданный итератор, применяя заданную функцию к каждому
    # элементу этого итератора. В данном случае, map разбивает по пробелу каждую строку
    # в `file`.
    for values in map(str.split, file):
        source = int(values[0])
        target = int(values[1])
        weight = float(values[2])

        edge = Edge(weight, target)
        graph[source].append(edge)

# Алгоритмом Дейкстры найдём кратчайшее расстояние из нужной нам точки до всех
# остальных точек графа.
distances = dijkstra(graph, 4)

# Выводим кратчайшее расстояние от начальной точки до конечной.
print(distances[100])  # -> "12479.0"

# Ответ: 12479
