# Создаём функцию с num(текущее чисо), target(число,
# которое мы хотим получить и exclude_nums(числа, которые мы НЕ хотим включать в
# траекторию вычеслений
def f(num: int, target: int, exclude_nums: list=[]) -> int:
    if num == target:
        return 1
    # Мы идём по возрастанию, поэтому, если число больше, чем нам надо, то
    # нам это число не подходит
    # или же это число есть в числах, которые мы хотим исключить
    if num > target or num in exclude_nums:
        return 0

    return f(num + 3, target, exclude_nums) + \
           f(num + 4, target, exclude_nums) + \
           f(num * 2, target, exclude_nums)

# Итак, по условию задачи нам нужно, чтобы при исходном числе 3 результатом являлось число 63,
# при этом траектория вычислений должна включать 15 или 26,
# и не должна включать числа 20 и 33
# У нас получаются такие исходы: 
# 1) В траектории есть и число 15 и число 26
# 2) В траектории есть 15 но нет 26
# 3) В траектории есть 26 но нет 15
# Вот, что у нас получается:

# 1) Есть и число 15 и число 26
f1 = f(3, 15) * f(15, 26, [20]) * f(26, 63, [33])
# 2) Есть 15 но нет 26
f2 = f(3, 15) * f(15, 63, [20, 26, 33])
# 3) Есть 26 но нет 15
f3 = f(3, 26, [15, 20]) * f(26, 63, [33])

# Далее мы должны сложить эти значения(сложить,
# потому знак сложения в комбинаторике можно заменить союзом ИЛИ)
# Получаем ответ
print(f1 + f2 + f3)
